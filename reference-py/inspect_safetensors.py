"""Inventory of model.safetensors → results/tensors.md, plus structural checks."""
import hashlib, json, math, struct, sys, collections
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "models/parakeet-redux"

def read_header(p):
    with open(p, "rb") as f:
        n = struct.unpack("<Q", f.read(8))[0]
        hdr = json.loads(f.read(n))
    hdr.pop("__metadata__", None)
    return hdr, 8 + n

def main():
    p = MODEL / "model.safetensors"
    hdr, base = read_header(p)
    sha = hashlib.sha256(p.read_bytes()).hexdigest()
    tern = json.load(open(MODEL / "ternary.json"))
    qmods = {m["name"]: m for m in tern["quantized_modules"]}
    numel = lambda s: math.prod(s) if s else 1

    problems = []
    # 1. every quantized module has qweight/scales with the expected shapes & dtypes
    for name, m in qmods.items():
        q, s = hdr.get(name + ".qweight"), hdr.get(name + ".scales")
        o, i, g = m["out_features"], m["in_features"], m["group_size"]
        if not q or q["dtype"] != "U8" or q["shape"] != [o, math.ceil(i / 5)]:
            problems.append(f"{name}.qweight bad: {q}")
        if not s or s["dtype"] != "F16" or s["shape"] != [o, i // g]:
            problems.append(f"{name}.scales bad: {s}")
        if name + ".weight" in hdr:
            problems.append(f"{name}.weight present alongside qweight")
        if m["has_bias"] and name + ".bias" not in hdr:
            problems.append(f"{name}.bias missing")
    # 2. counts
    dense = {k: v for k, v in hdr.items() if not (k.endswith(".qweight") or k.endswith(".scales"))}
    n_dense = sum(numel(v["shape"]) for v in dense.values())
    n_q = sum(m["in_features"] * m["out_features"] for m in qmods.values())
    if n_dense != tern["n_dense_params"]:
        problems.append(f"dense params {n_dense} != ternary.json {tern['n_dense_params']}")
    if n_q != tern["n_quantized_params"]:
        problems.append(f"quantized params {n_q} != ternary.json {tern['n_quantized_params']}")
    # 3. blank row of the decoder embedding (blank_as_pad in NeMo → zero vector)
    emb = hdr["decoder.embedding.weight"]
    with open(p, "rb") as f:
        f.seek(base + emb["data_offsets"][0])
        raw = np.frombuffer(f.read(emb["data_offsets"][1] - emb["data_offsets"][0]), dtype=np.float16).reshape(emb["shape"])
    blank_row_zero = bool(np.all(raw[8192] == 0))

    by_dtype = collections.Counter(v["dtype"] for v in hdr.values())
    bytes_by_dtype = collections.Counter()
    for v in hdr.values():
        bytes_by_dtype[v["dtype"]] += v["data_offsets"][1] - v["data_offsets"][0]

    lines = ["# Tensor inventory — `model.safetensors`", "",
             f"Generated by `reference-py/inspect_safetensors.py`. File sha256 `{sha}`, {p.stat().st_size:,} bytes, {len(hdr)} tensors.", "",
             "| dtype | tensors | bytes |", "|---|---|---|"]
    for d, n in sorted(by_dtype.items()):
        lines.append(f"| {d} | {n} | {bytes_by_dtype[d]:,} |")
    lines += ["", f"- dense params: {n_dense:,} (ternary.json: {tern['n_dense_params']:,})",
              f"- ternary params: {n_q:,} (ternary.json: {tern['n_quantized_params']:,})",
              f"- `decoder.embedding.weight[8192]` (blank) is all zeros: **{blank_row_zero}**",
              f"- structural problems: **{len(problems)}**"] + [f"  - {x}" for x in problems]
    lines += ["", "## Confirmed packed shapes", "",
              "`qweight`: `[out_features, ceil(in_features/5)]` U8 · `scales`: `[out_features, in_features/128]` F16 · no bias on ternary modules.", "",
              "## All tensors (encoder layers 1–23 omitted; identical to layer 0)", "",
              "| name | dtype | shape |", "|---|---|---|"]
    for k in sorted(hdr):
        if k.startswith("encoder.layers.") and not k.startswith("encoder.layers.0."):
            continue
        lines.append(f"| `{k}` | {hdr[k]['dtype']} | {hdr[k]['shape']} |")
    out = ROOT / "results/tensors.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}; problems={len(problems)}; blank_row_zero={blank_row_zero}; dense={n_dense}; ternary={n_q}")
    for x in problems: print("  PROBLEM:", x)
    return 1 if problems else 0

if __name__ == "__main__":
    sys.exit(main())
